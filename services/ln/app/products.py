def get_product(product_id: str) -> LoanProduct | None:
    for p in PRODUCTS:
        if p.product_id == product_id and p.active:
            return p
    return None


def list_products(category: str | None = None, risk_level: str | None = None) -> list[LoanProduct]:
    out = [p for p in PRODUCTS if p.active]
    if category:
        out = [p for p in out if p.category == category]
    if risk_level:
        out = [p for p in out if p.risk_level == risk_level]
    return out